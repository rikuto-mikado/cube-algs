export function categoryLabel(category: string, lang: Language): string {
  return lang === 'ja' ? (CATEGORY_JA[category] ?? category) : category;
}

export function statusKey(s: LearningStatus): StringKey {
  return s === 'unseen' ? 'statusUnseen' : s === 'learning' ? 'statusLearning' : 'statusMastered';
}

export function stageBlurbKey(s: Stage): StringKey {
  return s === 'F2L' ? 'stageBlurbF2L' : s === 'OLL' ? 'stageBlurbOLL' : 'stageBlurbPLL';
}

const ERROR_KEYS: Readonly<Record<string, StringKey>> = {
  unrecognised: 'errUnrecognised',
  unexpected: 'errUnexpected',
  missing: 'errMissing',
  'empty-group': 'errEmptyGroup',
  'too-long': 'errTooLong',
  empty: 'sandboxEmpty',
};

/** Localised description of a notation validation error. */
export function notationErrorText(
  lang: Language,
  e: { readonly code: string; readonly token: string; readonly position: number },
): string {
  const main = translate(lang, ERROR_KEYS[e.code] ?? 'sandboxError', { token: e.token });
  return e.position >= 0 ? `${main} (${translate(lang, 'errAt', { n: e.position + 1 })})` : main;
}

/** Looks up a string and fills `{name}` style placeholders. */
export function translate(
  lang: Language,
  key: StringKey,
  vars?: Readonly<Record<string, string | number>>,
): string {
  const template = DICTIONARIES[lang][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
